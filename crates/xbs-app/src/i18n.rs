//! independent of the UI locale (spec items 85-89, 106/116/126...).

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Lang {
    En,
    Ru,
    ZhHans,
    Kk,
}

impl Lang {
    pub fn code(self) -> &'static str {
        match self {
            Lang::En => "en",
            Lang::Ru => "ru",
            Lang::ZhHans => "zh-Hans",
            Lang::Kk => "kk",
        }
    }
    pub fn from_code(s: &str) -> Option<Lang> {
        match s {
            "en" => Some(Lang::En),
            "ru" => Some(Lang::Ru),
            "zh-Hans" | "zh" => Some(Lang::ZhHans),
            "kk" => Some(Lang::Kk),
            _ => None,
        }
    }
    pub fn label(self) -> &'static str {
        match self {
            Lang::En => "English",
            Lang::Ru => "Русский",
            Lang::ZhHans => "简体中文",
            Lang::Kk => "Қазақша",
        }
    }
    pub const ALL: [Lang; 4] = [Lang::En, Lang::Ru, Lang::ZhHans, Lang::Kk];
}

