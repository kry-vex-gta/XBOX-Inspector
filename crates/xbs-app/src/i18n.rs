pub fn stage(lang: Lang, message: &str) -> String {
    for (name, key) in [
        ("Инвентаризация", "inventory"),
        ("Конфигурация и preflight", "configuration"),
        ("Полный SHA-256", "full_hash"),
        ("Заголовки RPF9", "rpf_header"),
        ("Таблицы RDS5/ETPF", "rds5_table"),
        ("Проверка индексированных диапазонов", "indexed"),
        ("Поиск открытых потоков", "discover"),
        ("Диапазоны", "range_item"),
        ("Индекс", "index_item"),
        ("ZLIB-поиск", "zlib_item"),
        ("Bink-поиск", "bink_item"),
        ("Видеоиндекс", "video_item"),
    ] {
        if let Some(suffix) = message.strip_prefix(name) {
            if suffix.is_empty() || suffix.starts_with(' ') {
                return format!("{}{suffix}", tr(lang, key));
            }
        }
    }
    message.to_owned()
}
